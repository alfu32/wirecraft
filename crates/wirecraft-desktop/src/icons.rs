pub fn for_button(id: &str) -> &'static str {
    match id {
        "new" => "new",
        "open" | "import-archetype" => "open",
        "save" | "save-as" | "save-archetype" => "save",
        "undo" => "undo",
        "redo" => "redo",
        "select" => "select",
        "node" | "Designer" => "node",
        "type" | "Archetypes" => "type",
        "link" => "link",
        "fit" => "fit",
        "up" => "up",
        "copy-graph" | "copy-fiches" | "copy-mcp" => "copy",
        "cut-graph" => "cut",
        "paste-graph" => "paste",
        "Export" | "sheet" => "sheet",
        "Editor" | "Tools" => "code",
        "Analysis" => "analysis",
        "Project Management" => "board",
        "MCP" => "server",
        "apply" => "check",
        _ => "",
    }
}
